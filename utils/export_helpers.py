"""
Export helpers for downloading filtered prediction results, metric summaries, and CSV reports.
"""
from typing import Optional
import io
import pandas as pd


def dataframe_to_csv_bytes(df: pd.DataFrame, index: bool = False) -> bytes:
    """Converts a pandas DataFrame to CSV bytes for Streamlit download."""
    buf = io.StringIO()
    df.to_csv(buf, index=index)
    return buf.getvalue().encode("utf-8")


def generate_experiment_markdown_report(
    df_overall: pd.DataFrame,
    df_lang: pd.DataFrame,
    df_char: pd.DataFrame,
) -> str:
    """Generates a markdown summary text of the experimental results."""
    lines = [
        "# Multilingual Review Intelligence — Experimental Report Summary",
        "",
        "## 1. Overall Evaluation Metrics",
        "",
        df_overall.to_markdown(index=False),
        "",
        "## 2. Language-Wise Performance Breakdown",
        "",
        df_lang.to_markdown(index=False),
        "",
        "## 3. Model Characteristics & Architecture",
        "",
        df_char.to_markdown(index=False),
        "",
        "---",
        "Generated by Multilingual Review Intelligence Dashboard",
    ]
    return "\n".join(lines)
